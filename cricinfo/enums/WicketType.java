package cricinfo.enums;

public enum WicketType {
    BOWLED,        // ball hits stumps
    CAUGHT,        // fielder catches
    LBW,           // leg before wicket
    RUN_OUT,       // batsman short of crease
    STUMPED,       // keeper removes bails with batsman out of crease
    HIT_WICKET     // batsman dislodges own stumps
}
